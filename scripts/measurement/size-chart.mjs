#!/usr/bin/env node
// Writes the JACKETEK development size chart from scripts/measurement/size-system.mjs:
//   garment-spec/jacketek-development-size-chart-v0.1.json / .md
// Master Spec v0.2 carries the same chart (scripts/measurement/source-matrix.mjs — run it too).
// APPROVED FOR DEVELOPMENT USE — NOT PRODUCTION APPROVED.
import { writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { CLASS, SIZES, chartJson } from "./size-system.mjs";

const ROOT = resolve(import.meta.dirname, "..", "..");
const c = chartJson();
const row = (id) => c.table.find((r) => r.id === id);
// Rules the chart must keep.
if (c.core.map((d) => d.id).join() !== "B01,B06" || c.core.some((d) => d.class !== CLASS.TARGET)) throw new Error("core targets must be B01, B06");
if (c.productionApproved !== false || c.approval.production.approved !== false || /PRODUCTION_APPROVED/.test(JSON.stringify(c))) throw new Error("production approval in the chart");
if (row("S02").bySize.M !== null) throw new Error("S02 must stay formula-only until S09 is set");
if (SIZES.some((s) => row("B03").bySize[s] !== row("B01").bySize[s])) throw new Error("B03 must equal B01");
writeFileSync(join(ROOT, "garment-spec", "jacketek-development-size-chart-v0.1.json"), `${JSON.stringify(c, null, 2)}\n`);

const f = (v) => (v === null || v === undefined ? "—" : typeof v === "number" ? v.toFixed(1) : v);
const raw = (v) => (v === null || v === undefined ? "—" : String(v));
const sign = (v) => { const x = Math.round(v * 10) / 10; return `${x > 0 ? "+" : x < 0 ? "−" : "±"}${Math.abs(x).toFixed(1)}`; };
const t = (head, rows) => [`| ${head.join(" | ")} |`, `|${head.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${r.join(" | ")} |`)].join("\n");
const L = [];
L.push(`# JACKETEK development size chart ${c.version}`, "");
L.push(`**${c.status}.** Approved for development use by ${c.approval.developmentUse.by} on ${c.approval.developmentUse.date} — ${c.approval.developmentUse.scope} **Production:** not approved (${c.approval.production.requires})`, "");
L.push(`Generated by \`scripts/measurement/size-chart.mjs\` from \`scripts/measurement/size-system.mjs\`; do not edit by hand. Units: ${c.units}. Anchor size: **${c.anchorSize}**. Shoulder: **${c.shoulderConstruction}**. ${c.rounding}`, "");
L.push("## Source hierarchy (never averaged)", "", t(["Source", "Role", "Use"], c.sourceHierarchy.map((s) => [s.source, `**${s.role}**`, s.use])), "", `Excluded: ${c.excluded.join("; ")}.`, "");
L.push("## Classes", "", t(["Class", "Meaning"], Object.entries(c.classes)), "");
L.push("## Size table (XS–XXL)", "", t(["POM", "Measurement", "Class", ...SIZES, "Golden Bear grade", "JACKETEK grade"], c.table.map((r) => [r.id, r.name, r.label, ...SIZES.map((s) => (r.bySize[s] === null ? (s === c.anchorSize ? "**S02-E − S09**" : "S02-E − S09") : s === c.anchorSize ? `**${f(r.bySize[s])}**` : f(r.bySize[s]))), raw(r.goldenBearGradeCm), raw(r.gradePerSizeCm)])), "");
L.push(c.notInRange, "");
L.push("## Core development targets (M)", "");
for (const d of c.core) {
  L.push(`### ${d.id} ${d.name} — **${d.M.toFixed(1)} cm** (${d.class})`, "");
  L.push(t(["Source", "M", "Step / size", "Note"], [["Golden Bear", raw(d.sources.goldenBear.M), raw(d.sources.goldenBear.step), d.sources.goldenBear.note], ["Supplied chart", raw(d.sources.userChart.M), "not recorded", d.sources.userChart.note], ["S.i. Graphics", "—", "—", d.sources.si]]), "");
  L.push(`- **Method:** ${d.method}`, `- **Choice:** ${d.choice}`, `- **Grading:** ${d.formula}. Golden Bear grade ${d.grade.goldenBear} cm; JACKETEK grade ${d.grade.jacketek} cm.`, `- **Confidence:** ${d.confidence}`, "");
}
const e = c.shoulderExtension;
L.push(`## SC-1 dropped-shoulder extension — **${e.valuePerSideCm.toFixed(1)} cm per side, every size**`, "", `${e.status}.`, "", `Rule: ${e.rule}`, "", `History: ${e.replaces}`, "", ...e.why.map((w) => `- ${w}`), "");
L.push("## Derived dimensions", "");
for (const d of c.derived) {
  L.push(`### ${d.id} ${d.name} — ${d.M === null ? "**formula only**" : `**${d.M.toFixed(1)} cm**`} (${d.label})`, "");
  L.push(`- **Formula:** ${d.formula} → ${d.worked}`);
  if (d.roles) L.push(...d.roles.map((x) => `- ${x}`));
  if (d.assumptions) L.push(...d.assumptions.map((a) => `- **Assumption:** ${a}`));
  if (d.missing) L.push(`- **Missing:** ${d.missing}`);
  if (d.sampleChecks) L.push(`- **M sample must validate:** ${d.sampleChecks.join("; ")}.`);
  if (d.patternMakerRule) L.push(`- **Pattern maker:** ${d.patternMakerRule}`);
  L.push(`- **Sources:** Golden Bear ${raw(d.sources.goldenBear.M)} (${d.sources.goldenBear.note}); supplied chart ${raw(d.sources.userChart.M)} (${d.sources.userChart.note}); S.i.: ${d.sources.si}`);
  L.push(`- **Grade:** Golden Bear ${raw(d.grade.goldenBear)} cm; JACKETEK ${raw(d.grade.jacketek)} cm per size.`, `- **Depends on:** ${d.dependsOn.join(", ")}`, `- **Confidence:** ${d.confidence}`, "");
}
L.push("## Pattern-maker dimensions (PATTERN_MAKER_SET + SAMPLE_VALIDATION)", "", t(["POMs", "Why"], c.patternMaker.map((p) => [p.ids.join(", "), p.what])), "");
L.push("## Sample validation", "", c.sampleValidation.rule, "", ...c.sampleValidation.sampleOnly.map((x) => `- ${x.id}: ${x.note}`), "");
L.push("## Golden Bear Classic Fit (reference, cm, set-in)", "", t(["", ...SIZES, "Step"], c.goldenBearReference.map((r) => [`${r.id} ${r.name}`, ...SIZES.map((s) => raw(r.bySize[s])), raw(r.step)])), "");
const gbM = Object.fromEntries(c.goldenBearReference.map((r) => [r.id, r.M]));
const M = (id) => row(id).bySize.M;
L.push("## Comparison at M", "", t(["Measurement", "JACKETEK", "Golden Bear", "Δ vs GB", "Supplied chart", "Δ vs chart"], [
  ["Half chest (B01)", f(M("B01")), raw(gbM.B01), sign(M("B01") - gbM.B01), "61", sign(M("B01") - 61)],
  ["Centre-back length (B06)", f(M("B06")), raw(gbM.B06), sign(M("B06") - gbM.B06), "68", sign(M("B06") - 68)],
  ["Across shoulder (B09)", `${f(M("B09"))} (dropped)`, `${gbM.B09} (set-in)`, `${sign(M("B09") - gbM.B09)} (= 2 × SC-1)`, "50 (construction unknown)", sign(M("B09") - 50)],
  ["Sleeve SP → cuff edge (S02-E)", f(M("S02-E")), "— (publishes CB sleeve only)", "—", "51 (method unverified — not used)", "not comparable"],
  ["Sleeve CB → cuff edge (S01-E, reference)", f(M("S01")), raw(gbM.S01), sign(M("S01") - gbM.S01), "—", "—"],
  ["Sleeve SP → cuff seam (S02, primary)", "S02-E − S09", "—", "—", "—", "—"],
]), "");
L.push("APPROVED FOR DEVELOPMENT USE. Nothing in this chart is production approved.");
writeFileSync(join(ROOT, "garment-spec", "jacketek-development-size-chart-v0.1.md"), `${L.join("\n")}\n`);
console.log("development size chart v0.1 written");
